#!/usr/bin/env python3
"""compat.py - docs/COMPAT.md from target/matrix/<distro>.json (plan WP31).

A feature is "pass" when every test of it passed, "degraded" when it is
missing for a reason the daemon reports ("not available ..." in
`sysscope status`, or Glasshouse refusing correctly), "fail" otherwise.
Every "fail" needs an entry in docs/UNVERIFIED.md (checked here)."""
import glob, json, os, re, sys

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
order = ["debian12", "ubuntu2204", "ubuntu2404", "fedora", "arch"]
runs = {json.load(open(p))["distro"]: json.load(open(p))
        for p in glob.glob(f"{here}/target/matrix/*.json")}
dists = [d for d in order if d in runs]
if not dists:
    sys.exit("no target/matrix/*.json: run make vm-matrix")

def groups(tests):
    g = {}
    for name, res in tests.items():
        suite, test = name.split("::", 1)
        if suite == "rules_e2e":
            rules = re.findall(r"r0(\d\d)", test)
            col = "R" + "+R".join("0" + r for r in rules) if rules else "rules: " + test
        elif suite == "follow" and ("loss" in test or "flood" in test):
            col = "loss identity"
        elif suite == "follow":
            col = "follow"
        elif suite == "cli":
            col = "CLI export" if "export" in test else "CLI"
        else:
            col = suite
        g.setdefault(col, []).append((test, res))
    return g

def cell(run, col, items):
    bad = [t for t, r in items if r != "ok"]
    if not bad:
        return "pass"
    notes = " ".join(run["unavailable"])
    if col.startswith("R011") and "ptrace" in notes:
        return "degraded: " + next(n for n in run["unavailable"] if "ptrace" in n)
    return "fail: " + ", ".join(bad)

cols, table = [], {}
for d in dists:
    g = groups(runs[d]["tests"])
    for c in g:
        if c not in cols:
            cols.append(c)
    table[d] = {c: cell(runs[d], c, g[c]) for c in g}
    gh = runs[d]["glasshouse"]
    if gh == "WP24 GLASSHOUSE PASS":
        table[d]["Glasshouse demo"] = "pass"
    elif gh == "WP24 UNAVAILABLE-CORRECTLY PASS":
        why = next((n for n in runs[d]["unavailable"] if n.startswith("glasshouse")), "glasshouse: not available")
        table[d]["Glasshouse demo"] = "degraded: " + why
    else:
        table[d]["Glasshouse demo"] = "fail: " + (gh or "no result")
cols = [c for c in cols if not c.startswith("R")] + sorted(c for c in cols if c.startswith("R"))
cols.append("Glasshouse demo")

o = ["# Compatibility (plan WP31)", "",
     "Generated by `make vm-matrix` (vm/matrix.sh, scripts/compat.py): the package from",
     "`make package` (built on ubuntu2204, glibc 2.35) is installed in a fresh guest of each",
     "distribution, and the root itest subset, one simulator per rule, the CLI export and",
     "the Glasshouse demo run against the installed binaries.",
     "\"degraded\" = not available there, with the reason SysScope itself reports.", ""]
o.append("| feature | " + " | ".join(dists) + " |")
o.append("|---|" + "---|" * len(dists))
o.append("| system | " + " | ".join(runs[d]["pretty"] for d in dists) + " |")
o.append("| kernel | " + " | ".join(runs[d]["kernel"] for d in dists) + " |")
o.append("| package installs | " + " | ".join("pass" if runs[d]["installed"] else "fail" for d in dists) + " |")
for c in cols:
    o.append(f"| {c} | " + " | ".join(table[d].get(c, "not run") for d in dists) + " |")
o.append("| dmesg (bpf/BUG/WARNING/RCU) | " + " | ".join("clean" if runs[d]["dmesg_bad_lines"] == 0 else f"{runs[d]['dmesg_bad_lines']} lines" for d in dists) + " |")
o += ["", "Features each daemon reported as not available:", ""]
for d in dists:
    for n in runs[d]["unavailable"] or ["(none)"]:
        o.append(f"- {d}: {n}")
fails = [(d, c, v) for d in dists for c, v in table[d].items() if v.startswith("fail")]
unv = open(f"{here}/docs/UNVERIFIED.md").read()
untracked = [(d, c) for d, c, _ in fails if f"{d} {c}" not in unv]
o += ["", f"Failures: {len(fails)}; without an entry in docs/UNVERIFIED.md: {len(untracked)}.", ""]
open(f"{here}/docs/COMPAT.md", "w").write("\n".join(o))
print("\n".join(o))
sys.exit(1 if untracked else 0)
