#!/usr/bin/env bash
# fp-eval.sh host|vm-guest|report - false-positive evaluation (plan 5.7(3), WP18).
#   host      record every benign workload on this machine (daemon as root
#             via sudo, workloads as you), replay each through the detector
#   vm-guest  the same inside a test VM (run by `make fp-eval` through vm/run.sh)
#   report    write docs/FP_REPORT.md from target/fp/{host,vm}/*.summary.json
# Recordings go to target/fp/<where>/<workload>.events.jsonl. Host recordings
# hold everything the machine did meanwhile, so they are never committed;
# VM recordings become regression fixtures (fixtures/benign/).
set -euo pipefail
mode="${1:?host|vm-guest|report}"
here="$(cd "$(dirname "$0")/.." && pwd)"

summarise() { # recording -> summary json on stdout
    python3 - "$1" "$2" <<'PY'
import json, subprocess, sys
rec, cli = sys.argv[1], sys.argv[2]
lines = [l for l in open(rec, encoding="utf-8", errors="replace") if l.strip()]
ts = []
for l in lines[1:]:
    try:
        v = json.loads(l)
    except ValueError:
        continue
    t = (v.get("event") or {}).get("ts_ns") or v.get("ts_ns")
    if t:
        ts.append(t)
dur = (max(ts) - min(ts)) / 1e9 if len(ts) > 1 else 0.0
out = subprocess.run([cli, "--json", "replay", rec], capture_output=True, text=True)
if out.returncode != 0:
    sys.exit("replay failed: " + out.stderr[-500:])
r = json.loads(out.stdout)
# Band = the highest score the process reached: at an alert (taken when it
# happened) or in the final snapshot. Scores decay and exited processes
# leave the state, so the final snapshot alone understates long recordings.
score = {(p["key"]["tgid"], p["key"]["start"]): p["score"] for p in r["snapshot"]["procs"]}
for a in r.get("alert_scores", []):
    k = (a["proc"]["tgid"], a["proc"]["start"])
    score[k] = max(score.get(k, 0), a["score"])
found = []
for f in r["findings"]:
    s = score.get((f["proc"]["tgid"], f["proc"]["start"]), 0)
    band = "high" if s >= 60 else "suspicious" if s >= 30 else "low"
    found.append({"rule": f["rule"], "subject": f["subject"], "exe": f["exe"], "score": s,
                  "band": band, "summary": f["summary"]})
print(json.dumps({"recording": rec.split("/")[-1], "seconds": round(dur, 1), "events": len(lines) - 1,
                  "findings": found}))
PY
}

record() { # where bin_dir workload-name [run-as-root]
    local where=$1 bin=$2 w=$3 asroot=${4:-}
    local out="$here/target/fp/$where" wd
    # Work happens in an ordinary directory, as real builds do (a temp dir
    # would make every freshly built program an honest R002 hit).
    mkdir -p "$out" "$WORK"; wd=$(mktemp -d "$WORK/$w.XXXX")
    "$here/testkit/benign/$w.sh" setup "$wd" > /dev/null
    local rec="$out/$w.events.jsonl"
    rm -f "$rec"
    $SUDO "$bin/sysscoped" --dev --record "$rec" > /dev/null 2> "$out/$w.daemon.log" &
    local dpid=$!
    for _ in $(seq 1 100); do grep -q serving "$out/$w.daemon.log" && break; sleep 0.1; done
    sleep 2
    if [ -n "$asroot" ]; then $SUDO "$here/testkit/benign/$w.sh" run "$wd" || echo "$w: workload failed"
    else "$here/testkit/benign/$w.sh" run "$wd" || echo "$w: workload failed"; fi
    sleep 3
    $SUDO kill -INT "$(pgrep -f "sysscoped --dev --record $rec" | head -1)" 2>/dev/null || true
    wait "$dpid" 2>/dev/null || true
    $SUDO chmod 0644 "$rec"
    rm -rf "$wd"
    summarise "$rec" "$bin/sysscope" > "$out/$w.summary.json"
    python3 -c "import json,sys;s=json.load(open(sys.argv[1]));print('%-14s %7.1fs %8d events  findings: %s' % (sys.argv[2], s['seconds'], s['events'], [(f['rule'], f['band'], f['exe'].split('/')[-1]) for f in s['findings']]))" "$out/$w.summary.json" "$w"
}

case "$mode" in
host)
    SUDO="sudo -n"; WORK="$here/target/fp/work"
    sudo -n true || { echo "fp-eval host: needs passwordless sudo"; exit 1; }
    for w in git_build cargo_build tar_zip rsync_tree editor_save pip_venv curl_local; do
        record host "$here/target/release" "$w"
    done
    record host "$here/target/release" idle
    ;;
vm-guest)
    SUDO=""; WORK=/root/benign-work
    [ -f /etc/sysscope-test-vm ] || { echo "vm-guest mode runs only in a test VM"; exit 1; }
    for w in git_build tar_zip rsync_tree editor_save pip_venv curl_local ssh_localhost; do
        record vm /opt/sysscope/bin "$w"
    done
    record vm /opt/sysscope/bin apt root
    ;;
report)
    python3 - "$here" <<'PY'
import glob, json, os, sys
here = sys.argv[1]
rows, total_s, high, susp = [], 0.0, [], []
for where in ("host", "vm"):
    for p in sorted(glob.glob(f"{here}/target/fp/{where}/*.summary.json")):
        s = json.load(open(p))
        w = os.path.basename(p).replace(".summary.json", "")
        total_s += s["seconds"]
        rows.append((where, w, s))
        for f in s["findings"]:
            (high if f["band"] == "high" else susp if f["band"] == "suspicious" else []).append((where, w, f))
hours = total_s / 3600
o = ["# False-positive report (plan 5.7(3), WP18)", "",
     "Generated by `scripts/fp-eval.sh report` from recordings made by `make fp-eval`.",
     "Pass threshold: zero findings at \"high\"; at most 2 at \"suspicious\" per recorded hour,",
     "each allowlisted with a reason or documented as an accepted false positive.", "",
     f"Recorded: {total_s/60:.1f} minutes in {len(rows)} workloads; high findings: {len(high)};",
     f"suspicious findings: {len(susp)} ({len(susp)/max(hours,1e-9):.2f} per recorded hour).", "",
     "| where | workload | seconds | events | findings (rule, band, program) |", "|---|---|---|---|---|"]
for where, w, s in rows:
    fs = "; ".join(f"{f['rule']} {f['band']} {os.path.basename(f['exe'])}" for f in s["findings"]) or "none"
    o.append(f"| {where} | {w} | {s['seconds']} | {s['events']} | {fs} |")
o += ["", "## Findings", ""]
allf = [(wh, w, f) for wh, w, s in rows for f in s["findings"]]
if not allf:
    o.append("None.")
for wh, w, f in allf:
    o.append(f"- {wh}/{w}: {f['rule']} ({f['band']}, score {f['score']}) {os.path.basename(f['exe'])}: {f['summary']}")
ok = not high and len(susp) <= 2 * max(hours, 1e-9)
o += ["", f"Result: {'PASS' if ok else 'FAIL'} against the 5.7(3) threshold.", ""]
open(f"{here}/docs/FP_REPORT.md", "w").write("\n".join(o))
print("\n".join(o[6:9])); print(o[-2])
PY
    ;;
*) echo "usage: fp-eval.sh host|vm-guest|report"; exit 2 ;;
esac
